-- =============================================================================
-- Production patch: SP_VENDOR_CATEGORY for /vendor-category-create
-- Fixes ORA-00942 when app tries:
--   ALTER TABLE SP_VENDOR_CATEGORY ADD (PINNACLE_ACCOUNT_ID VARCHAR2(50))
-- Run as the CMS schema user (e.g. same user as DB_USERNAME in .env).
-- =============================================================================

-- 1) Create table if missing (includes PINNACLE_ACCOUNT_ID)
DECLARE
    v_cnt NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cnt
    FROM USER_TABLES
    WHERE TABLE_NAME = 'SP_VENDOR_CATEGORY';

    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE SP_VENDOR_CATEGORY (
                CATEGORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                PARENT_DEPARTMENT_ID NUMBER,
                CATEGORY_NAME VARCHAR2(2200),
                CATEGORY_DESCRIPTION VARCHAR2(2200),
                ENTRY_USER_ID NUMBER,
                CREATED_AT TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP,
                UPDATED_AT TIMESTAMP(6),
                BUDGET_TYPE VARCHAR2(500),
                Q_PARENT_DEPT_REQUIRED NUMBER DEFAULT 0,
                Q_HEAD_APPROVAL_REQUIRED NUMBER DEFAULT 0,
                ENTRY_USRNAME VARCHAR2(1000),
                Q_PARENT_DEPT_USERS VARCHAR2(300),
                Q_HEAD_APPROVAL_USERS VARCHAR2(2000),
                PINNACLE_ACCOUNT_ID VARCHAR2(50)
            )
        ';
    END IF;
END;
/

-- 2) If table already exists but column is missing, add it
DECLARE
    v_cnt NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_cnt
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'SP_VENDOR_CATEGORY'
      AND COLUMN_NAME = 'PINNACLE_ACCOUNT_ID';

    IF v_cnt = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE SP_VENDOR_CATEGORY ADD (PINNACLE_ACCOUNT_ID VARCHAR2(50))';
    END IF;
END;
/

COMMIT;
