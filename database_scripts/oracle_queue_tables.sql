-- Oracle queue infrastructure for Laravel database queue connection
-- Use this only if QUEUE_CONNECTION=database

-- 1) JOBS TABLE
CREATE TABLE jobs (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    queue VARCHAR2(255) NOT NULL,
    payload CLOB NOT NULL,
    attempts NUMBER(10) DEFAULT 0 NOT NULL,
    reserved_at NUMBER(10) NULL,
    available_at NUMBER(10) NOT NULL,
    created_at NUMBER(10) NOT NULL
);

CREATE INDEX jobs_queue_index ON jobs (queue);
CREATE INDEX jobs_queue_reserved_at_index ON jobs (queue, reserved_at);

-- 2) FAILED_JOBS TABLE
CREATE TABLE failed_jobs (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    uuid VARCHAR2(255) NOT NULL,
    connection CLOB NOT NULL,
    queue CLOB NOT NULL,
    payload CLOB NOT NULL,
    exception CLOB NOT NULL,
    failed_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX failed_jobs_uuid_unique ON failed_jobs (uuid);

